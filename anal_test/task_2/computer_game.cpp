#include <iostream>
#include <vector>
#include <queue>
#include <algorithm>

using namespace std;
// Псевдоним для 64-битного целого числа для хранения очков опыта
using ll = long long;

/**
 * @brief Решает задачу "Компьютерная игра".
 * @details Находит максимальное количество очков опыта, которое
 *			можно получить в игре, представленной в виде 
 *			ориентированного ациклического графа (DAG).
 *
 *          Алгоритм использует динамическое программирование на графе.
 *          1. Граф представляется списками смежности. Для 
 *			   топологической сортировки также вычисляются входящие 
 *			   степени (in-degree) каждой вершины.
 *          2. `dp[v]` хранит максимальное количество очков, которое можно набрать,
 *             завершив прохождение на уровне `v`.
 *          3. Вершины обрабатываются в топологическом порядке с использованием очереди.
 *             Это гарантирует, что при вычислении `dp[v]`, все значения `dp` для
 *             вершин, из которых можно попасть в `v`, уже вычислены.
 *          4. Рекуррентное соотношение:
 *             `dp[v] = max(dp[v], dp[u] + experience[v])`, где `u` - любая
 *             вершина с ребром `u -> v`.
 *          5. Итоговый ответ — это максимальное значение `dp[v]` среди всех
 *             финальных уровней (вершин без исходящих ребер).
 */
void solve() {
	int N, M;
	cin >> N >> M;

    // Вектор для хранения очков за каждый уровень. Используем 1-индексацию.
	vector<ll> experience(N + 1);
	for (int i = 1; i <= N; ++i) {
		std::cin >> experience[i];
	}

    // Структуры для представления графа и топологической сортировки
	vector<std::vector<int>> adj(N + 1); // Списки смежности
	vector<int> in_degree(N + 1, 0);     // Входящие степени вершин

    for (int i = 0; i < M; ++i) {
        int u, v;
        cin >> u >> v;
        adj[u].push_back(v);
        in_degree[v]++;
    }

	// DP-массив для хранения максимальных очков и очередь для топологической сортировки
	vector<ll> dp(N + 1, 0);
	queue<int> q;

    // Инициализация: находим все стартовые вершины (in-degree = 0)
    // и устанавливаем для них базовые значения DP.
    for (int i = 1; i <= N; ++i) {
        if (in_degree[i] == 0) {
            q.push(i);
            dp[i] = experience[i];
        }
    }

	// Основной цикл: обрабатываем вершины в топологическом порядке
	while (!q.empty()) {
        int u = q.front();
        q.pop();

        for (int v : adj[u]) {
            // Обновляем DP для соседа: путь через `u` может дать больше очков
            dp[v] = std::max(dp[v], dp[u] + experience[v]);
            
            // "Удаляем" ребро u->v и проверяем, не стал ли `v` новой вершиной без зависимостей
            in_degree[v]--;
            if (in_degree[v] == 0) {
                q.push(v);
            }
        }
	}

    // Поиск ответа: максимальное значение DP среди всех финальных уровней
    ll max_experience = 0;
    for (int i = 1; i <= N; ++i) {
        // Уровень финальный, если из него нет переходов (пустой список смежности)
        if (adj[i].empty()) {
            max_experience = std::max(max_experience, dp[i]);
        }
    }

    cout << max_experience << std::endl;
}

/**
 * @brief Главная функция для запуска решения.
 * @details Настраивает быстрый ввод-вывод и вызывает основную решающую функцию.
 * @return 0 при успешном выполнении.
 */
int main() {
	// Ускорение стандартных потоков ввода-вывода для производительности
	ios_base::sync_with_stdio(false);
	cin.tie(NULL);

    solve();

    return 0;
}