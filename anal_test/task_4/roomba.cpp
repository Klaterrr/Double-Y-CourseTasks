#include <iostream>
#include <string>
#include <algorithm>

using namespace std;
// Псевдоним для 64-битного целого числа, чтобы избежать переполнения
using ll = long long;

/**
 * @brief Решает задачу "Робот-пылесос" через сравнение двух глобальных стратегий.
 * @details Функция вычисляет минимальное время для очистки всех свободных клеток.
 *			Решение основано на выборе оптимальной из двух возможных стратегий:
 *
 *			Стратегия 1: "Стандартная уборка". Робот выполняет K-1 перемещений
 *			стоимостью x каждое и K очисток стоимостью y каждая.
 *			Общая стоимость: (K-1) * x + K * y.
 *
 *			Стратегия 2: "Альтернативный режим". Актуален, когда перемещение дорого.
 *			Робот чистит стартовую клетку (стоимость y), а затем для каждой из
 *			оставшихся K-1 клеток выполняет комплексную операцию
 *			"перемещение + очистка", стоимость которой равна 2y.
 *			Общая стоимость: y + (K - 1) * 2y.
 *
 *			Итоговый ответ - это минимум из стоимостей этих двух полных стратегий.
 */
void solve() {
	ll N, M, x, y;
	cin >> N >> M >> x >> y;

	ll empty_cell_count = 0;
	for (int i = 0; i < M; ++i) { // M - высота (количество строк)
        string row;
		cin >> row;
		for (char cell : row) {
			if (cell == '0') {
				empty_cell_count++;
			}
		}
	}

	if (empty_cell_count == 0) {
		cout << 0 << std::endl;
		return;
	}

	// Стоимость по Стратегии 1
	ll cost1 = (empty_cell_count - 1) * x + empty_cell_count * y;

	// Стоимость по Стратегии 2
	ll cost2 = y + (empty_cell_count - 1) * (2 * y);

	// Выбираем минимальную из двух
	ll total_time = min(cost1, cost2);

	cout << total_time << endl;
}

/**
 * @brief Главная функция для запуска решения.
 * @details Настраивает быстрый ввод-вывод и вызывает основную решающую функцию.
 * @return 0 при успешном выполнении.
 */
int main() {
	ios_base::sync_with_stdio(false);
	cin.tie(NULL);

	solve();

	return 0;
}