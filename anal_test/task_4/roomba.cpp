#include <iostream>
#include <vector>
#include <string>
#include <algorithm>

using namespace std;
// Псевдоним для 64-битного целого числа, чтобы избежать переполнения
using ll = long long;

/**
 * @brief Решает задачу "Робот-пылесос".
 * @details Функция вычисляет минимальное время, которое необходимо для очистки
 *			всех свободных клеток в квартире.
 *			Задача не требует сложного поиска пути. Так как все свободные клетки 
 *			связаны - минимальное количество перемещений для посещения всех K 
 *			свободных клеток всегда равно K-1.
 *			Алгоритм:
 *			1. Подсчитать общее количество свободных клеток (K).
 *			2. Стоимость очистки всех клеток фиксирована: K * y.
 *			3. Стоимость перемещения между двумя клетками (x) может быть
 *			   оптимизирована. Если x дороже, чем 2 * y, роботу "выгоднее"
 *			   заплатить за очистку двух клеток, чем за одно перемещение.
 *			   Поэтому эффективная стоимость одного перемещения равна min(x, 2 * y).
 *			4. Общее время перемещений: (K - 1) * min(x, 2 * y).
 *			5. Итоговое минимальное время = (K - 1) * min(x, 2 * y) + K * y.
 */
void solve() {
	ll N, M, x, y;
	cin >> N >> M >> x >> y;

	ll empty_cell_count = 0;
	for (int i = 0; i < M; ++i) { // M - высота (количество строк)
		string row;
		cin >> row;
		for (char cell : row) {
			if (cell == '0') {
				empty_cell_count++;
			}
		}
	}

	ll total_time = 0;
	if (empty_cell_count > 0) {
		// Вычисляем эффективную стоимость одного перемещения
		ll effective_move_cost = std::min(x, 2 * y);

		ll move_time = (empty_cell_count - 1) * effective_move_cost;
		ll clean_time = empty_cell_count * y;
		total_time = move_time + clean_time;
	}

	cout << total_time << std::endl;
}

/**
 * @brief Главная функция для запуска решения.
 * @details Настраивает быстрый ввод-вывод и вызывает основную решающую функцию.
 * @return 0 при успешном выполнении.
 */
int main() {
	// Ускорение IO для повышения производительности
	ios_base::sync_with_stdio(false);
	cin.tie(NULL);

	solve();

	return 0;
}